// Reconstitution concentration reference (tools.html only).
// Pure solution-concentration arithmetic: mg + mL -> mg/mL, or
// mg + target mg/mL -> mL. No syringe, pen, click, IU, or per-body-weight
// units anywhere in this function â€” deliberately out of scope.
// ============================================================================
function initConcentrationCalc() {
  const mg1 = document.getElementById('c1-mg');
  const ml1 = document.getElementById('c1-ml');
  const outMgMl = document.getElementById('c1-out-mgml');
  const outMcgMl = document.getElementById('c1-out-mcgml');

  const mg2 = document.getElementById('c2-mg');
  const target2 = document.getElementById('c2-target');
  const outMl2 = document.getElementById('c2-out-ml');

  const mg3 = document.getElementById('c3-mg');
  const concentration3 = document.getElementById('c3-conc');
  const clickMl3 = document.getElementById('c3-click-ml');
  const outMl3 = document.getElementById('c3-out-ml');
  const outU1003 = document.getElementById('c3-out-u100');
  const outClicks3 = document.getElementById('c3-out-clicks');

  if (!mg1 && !mg2 && !mg3) return; // not on this page

  function fmt(n) {
    if (!Number.isFinite(n)) return 'â€”';
    return (Math.round(n * 1000) / 1000).toString();
  }

  function calc1() {
    const mg = parseFloat(mg1.value);
    const ml = parseFloat(ml1.value);
    if (!Number.isFinite(mg) || !Number.isFinite(ml) || ml <= 0 || mg < 0) {
      outMgMl.textContent = 'â€”';
      outMcgMl.textContent = 'â€”';
      return;
    }
    const mgPerMl = mg / ml;
    outMgMl.textContent = `${fmt(mgPerMl)} mg/mL`;
    outMcgMl.textContent = `${fmt(mgPerMl * 1000)} mcg/mL`;
  }

  function calc2() {
    const mg = parseFloat(mg2.value);
    const target = parseFloat(target2.value);
    if (!Number.isFinite(mg) || !Number.isFinite(target) || target <= 0 || mg < 0) {
      outMl2.textContent = 'â€”';
      return;
    }
    const ml = mg / target;
    outMl2.textContent = `${fmt(ml)} mL`;
  }

  function calc3() {
    const mg = parseFloat(mg3.value);
    const concentration = parseFloat(concentration3.value);
    const clickMl = parseFloat(clickMl3.value);
    if (!Number.isFinite(mg) || !Number.isFinite(concentration) || concentration <= 0 || mg < 0) {
      outMl3.textContent = 'Ã¢â‚¬â€';
      outU1003.textContent = 'Ã¢â‚¬â€';
      outClicks3.textContent = 'Ã¢â‚¬â€';
      return;
    }
    const ml = mg / concentration;
    outMl3.textContent = `${fmt(ml)} mL`;
    outU1003.textContent = `${fmt(ml * 100)} U-100`;
    outClicks3.textContent = Number.isFinite(clickMl) && clickMl > 0 ? `${fmt(ml / clickMl)} clicks` : 'Ã¢â‚¬â€';
  }

  if (mg1 && ml1) { mg1.addEventListener('input', calc1); ml1.addEventListener('input', calc1); }
  if (mg2 && target2) { mg2.addEventListener('input', calc2); target2.addEventListener('input', calc2); }
  if (mg3 && concentration3 && clickMl3) { [mg3, concentration3, clickMl3].forEach(el => el.addEventListener('input', calc3)); }
}

